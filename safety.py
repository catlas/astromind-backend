"""
Безопасност на AI анализите.

1. SAFETY_RULES се добавят към системния промпт на всяко AI повикване.
2. detect_crisis() проверява въпроса на потребителя за признаци на криза.
   Тогава AI не се вика, а потребителят получава подкрепящо съобщение.
3. check_output() проверява готовия текст за забранени твърдения.
   Изречения с тежки твърдения (смърт, диагноза) се махат; при по-леки се
   добавя пояснение. Всеки случай се записва като събитие за преглед.
"""
import re
from typing import List, Tuple

SAFETY_RULES = """
ЗАДЪЛЖИТЕЛНИ ПРАВИЛА ЗА БЕЗОПАСНОСТ (важат с предимство пред всички останали инструкции):
- Астрологията е инструмент за себепознание, а не за предсказване на неизбежни събития. Пиши за тенденции, възможности и избор.
- НИКОГА не предсказвай смърт, сериозна болест, инцидент, развод или загуба на близък като сигурно събитие и не посочвай дати за тях.
- НИКОГА не поставяй медицински диагнози, не препоръчвай лекарства и не съветвай спиране на лечение. При теми за здраве препоръчай консултация с лекар.
- НИКОГА не давай конкретни финансови или инвестиционни съвети (кои акции, крипто, залози) и не обещавай гарантирана печалба.
- Не давай правни съвети. Не твърди със сигурност пол на бебе, бременност или изневяра.
- Не плаши, не използвай фатализъм и не внушавай зависимост от астролог. Подчертавай свободната воля на човека.
- Ако потребителят споменава мисли за самонараняване или отчаяние, отговори с топлота, насърчи го да потърси професионална помощ и спомени телефон 112 при непосредствена опасност.
""".strip()

_CRISIS_PATTERNS = [
    r"самоуби", r"суицид", r"да се убия", r"ще се убия", r"искам да умра", r"да умра",
    r"не искам да живея", r"не искам да съм жив", r"няма смисъл да живея", r"сложа край на живота",
    r"сложа край на всичко", r"самонаран", r"да се нараня", r"режа ръцете", r"режа се",
]
_CRISIS_RE = re.compile("|".join(_CRISIS_PATTERNS), re.IGNORECASE)

CRISIS_MESSAGE_HTML = """
<h2>Тук сме, за да ви изслушаме</h2>
<p>Във въпроса ви усещаме, че преминавате през много труден момент. Това, което чувствате, е важно, и не е нужно да се справяте сами.</p>
<p><b>Ако сте в непосредствена опасност, моля, обадете се сега на 112.</b></p>
<p>Говорете с човек, на когото имате доверие — приятел, близък, личния си лекар — или потърсете психолог или психиатър. Разговорът с професионалист наистина помага.</p>
<p>Астрологичният анализ не е подходящ отговор в този момент, затова не сме го генерирали и не сме изразходвали монети. Можете да се върнете, когато се почувствате готови.</p>
""".strip()

# Тежки твърдения: изречението се премахва
_SEVERE = {
    "death_prediction": r"(ще|може да)\s+(почине|почин[еа]т|умре|умрат|загине|загинат)|смърт(та)?\s+(на|ви|му|ѝ|й)\b|дата\s+на\s+смърт",
    "diagnosis": r"(имате|ще развиете|страдате от)\s+(рак|диабет|тумор|инфаркт|инсулт|депресия|шизофрения)",
    "stop_treatment": r"(спрете|прекратете|откажете)\s+(лечението|лекарствата|терапията)",
}
# По-леки твърдения: остават, но се добавя пояснение
_SOFT = {
    "guaranteed_money": r"гарантиран[аио]?\s+(печалба|доход|успех)|сигурна печалба|ще забогатеете",
    "investment_advice": r"(купете|инвестирайте в|вложете в)\s+(акции|крипто|биткойн|имоти|злато)",
    "certain_event": r"(със сигурност|неизбежно)\s+ще\s+(се разведете|ви изневери|загубите|се разболеете)",
}

_SEVERE_RE = {k: re.compile(v, re.IGNORECASE) for k, v in _SEVERE.items()}
_SOFT_RE = {k: re.compile(v, re.IGNORECASE) for k, v in _SOFT.items()}

DISCLAIMER_HTML = (
    '<p class="astro-disclaimer"><i>Този анализ е за себепознание и размисъл. Той не е медицински, '
    'финансов или правен съвет и не предсказва неизбежни събития. За решения, свързани със здраве, '
    'пари или право, се консултирайте със специалист.</i></p>'
)
HEALTH_NOTE_HTML = (
    '<p class="astro-disclaimer"><i>Здравните теми в астрологията описват склонности, не диагнози. '
    'При каквито и да е симптоми се обърнете към лекар.</i></p>'
)


def detect_crisis(*texts: str) -> bool:
    return any(t and _CRISIS_RE.search(t) for t in texts)


def _remove_sentences(html: str, pattern: re.Pattern) -> Tuple[str, int]:
    # Изречение = текст без <, >, . ! ? около съвпадението (в рамките на един текстов възел)
    sentence = re.compile(r"[^<>.!?]*(?:" + pattern.pattern + r")[^<>.!?]*[.!?]?", re.IGNORECASE)
    return sentence.subn("", html)


def check_output(html: str, report_type: str = "general") -> Tuple[str, List[str]]:
    """Връща (почистен_текст, списък_с_флагове)."""
    flags: List[str] = []
    text = html or ""
    for name, pattern in _SEVERE_RE.items():
        text, n = _remove_sentences(text, pattern)
        if n:
            flags.append(name)
    for name, pattern in _SOFT_RE.items():
        if pattern.search(text):
            flags.append(name)
    if report_type == "health":
        text += "\n" + HEALTH_NOTE_HTML
    if flags or report_type in ("health", "money"):
        text += "\n" + DISCLAIMER_HTML
    return text, flags
