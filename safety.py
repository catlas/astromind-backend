_HEALTH_ACT = (r"(?:здравн\w+\s+(?:решени\w+|действи\w+|въпрос\w+|проблем\w+|процедур\w+|стъпк\w+)|лекар(?:я|ю|ите|и|ска|ски|ско)?|лекарск\w+|"
               r"лечени\w+|терапи\w+|операци\w+|медицинск\w+|диагностик\w+|ваксинаци\w+|рехабилитаци\w+|прием\w*\s+на\s+лекарств\w+|"
               r"преглед\w*\s+(?:при|у)\s+(?:лекар|специалист)\w*|профилактичен\s+преглед|изследван\w+\s+(?:при|у|за\s+здраве)|"
               r"кръвни\s+изследван\w+|час\s+при\s+(?:лекар|доктор)\w*|доктор\w*|болниц\w+)")
_HEALTH_ACT_RE = re.compile(r"(?<![\w])" + _HEALTH_ACT, re.IGNORECASE)
_DELAY_RE = re.compile(
    r"(?<![\w])(?:не\s+(?:взимайте|вземайте|взимай|вземай|започвайте|започвай|предприемайте|предприемай|насрочвайте|насрочвай|"
    r"посещавайте|посещавай|ходете|ходи|правете|прави|се\s+подлагайте|се\s+подлагай|решавайте|решавай|стартирайте|стартирай)|"
    r"отложете|отложи|отлагайте|изчакайте|изчакай|почакайте|почакай|оставете\s+за\s+по-късно|да\s+се\s+отложи\w*|да\s+се\s+изчака\w*)(?![\w])",
    re.IGNORECASE)
_ASTRO_OR_TIME_RE = re.compile(
    r"(?<![\w])(?:ретроград\w*|транзит\w*|Слънце\w*|Луна\w*|Луната|Меркурий\w*|Венера\w*|Марс\w*|Юпитер\w*|Сатурн\w*|Уран\w*|Нептун\w*|Плутон\w*|"
    r"квадрат\w*|опозиц\w*|тригон\w*|секстил\w*|съвпад\w*|аспект\w*|лунаци\w*|новолуни\w*|пълнолуни\w*|затъмнени\w*|астролог\w*|планет\w*|"
    r"около|до|след|през|докато|няколко\s+дни|седмиц\w*|месец\w*|период\w*|\d{1,2}\s+(?:януари|февруари|март|април|май|юни|юли|август|септември|октомври|ноември|декември))(?![\w])",
    re.IGNORECASE)
_SAFE_MARK_RE = re.compile(r"без\s+отлагане|незабавно|веднага|спешн\w+|не\s+(?:отлагайте|изчаквайте|отлагай|изчаквай)|при\s+симптом\w+\s+(?:потърсете|се\s+обърнете)", re.IGNORECASE)
_NEG_BEFORE_RE = re.compile(r"(?<![\w])не\s+(?:отлагайте|отлагай|изчаквайте|изчаквай)", re.IGNORECASE)

HEALTH_DELAY_ADVICE = ("Не отлагай консултация, преглед, изследване или лечение заради астрологичен период или дата. Преформулирай: при симптоми или "
                       "планирани прегледи – по обичайния ред, без астрологична пречка; полезните навици (пауза без екрани, сън, организация на деня) остават.")
HEALTH_DELAY_REPLACEMENT = ("Ако имате симптоми или предстои преглед, изследване или лечение, не ги отлагайте заради астрологичен период: "
                            "консултирайте се с лекар по обичайния ред.")

_ORGAN = (r"(?:стомах\w*|черен\s+дроб|черния\s+дроб|бъбрек\w*|бъбреци|сърц\w+|сърдечн\w+|щитовидн\w+|панкреас\w*|бял\s+дроб|бели\s+дробове|белите\s+дробове|"
          r"жлъчк\w*|черва\w*|простат\w+|яйчник\w*|матк\w+|кръвно|кръвна\s+захар|кръвното\s+налягане|ставите|гръбнак\w*|имунитет\w*|кожа\w*)")
_FACTUAL_ORGAN_RE = re.compile(
    rf"(?:(?:имате|имаш|страдате|страдаш|ви\s+е|ти\s+е|са\s+ви|са\s+ти)\s+(?:\w+\s+){{0,2}}(?:слаб\w*|уязвим\w*|проблем\w*|заболяван\w*|възпал\w*)|"
    rf"ще\s+(?:причини|предизвика|доведе\s+до|получите|развиете|имате|страдате|заболее|заболеят)|"
    rf"слаб\w*\s+(?:място|места|звено)|(?:е|са)\s+уязвим\w*|физическа\s+уязвимост|доказан\w*\s+уязвимост)", re.IGNORECASE)
_ORGAN_RE = re.compile(r"(?<![\w])" + _ORGAN, re.IGNORECASE)
_HEDGE_HEALTH_RE = re.compile(r"символи\w*|тенденци\w*|чувствителност|склонност|възможно|може\s+да|понякога|не\s+е\s+диагноза|в\s+астрологичен\s+смисъл|темата\s+за|свързва\w*|подсказва\w*|\bако\b|без\s+да", re.IGNORECASE)

_SENTENCE_SPLIT_RE = re.compile(r"(?<=[.!?])\s+|\n+")


def _plain_sentences(text: str) -> List[str]:
    plain = re.sub(r"<[^>]+>", "\n", text or "")
    return [x.strip() for x in _SENTENCE_SPLIT_RE.split(plain) if x and x.strip()]


def health_findings(text: str) -> List[Tuple[str, str]]:
    """(код, изречение): health_delay - отлагане на медицинска помощ заради астрологичен период; health_organ - органи или болести като факт."""
    found: List[Tuple[str, str]] = []
    sentences = _plain_sentences(text)
    for i, sentence in enumerate(sentences):
        if _SAFE_MARK_RE.search(sentence):
            continue
        delay = _DELAY_RE.search(sentence)
        if delay and not _NEG_BEFORE_RE.search(sentence):
            context = sentence if _HEALTH_ACT_RE.search(sentence) else ""
            # „Изчакайте няколко дни.“ след изречение за здравни решения е същото отлагане
            if not context and i and re.match(r"\s*(?:изчакайте|изчакай|почакайте|отложете|отлагайте)", sentence, re.IGNORECASE) \
                    and _HEALTH_ACT_RE.search(sentences[i - 1]) and _DELAY_RE.search(sentences[i - 1]):
                context = sentences[i - 1]
            if context and (_ASTRO_OR_TIME_RE.search(sentence) or _ASTRO_OR_TIME_RE.search(context)):
                found.append(("health_delay", sentence[:200]))
                continue
        if _ORGAN_RE.search(sentence) and _FACTUAL_ORGAN_RE.search(sentence) and not _HEDGE_HEALTH_RE.search(sentence):
            found.append(("health_organ", sentence[:200]))
    return found


def replace_health_delays(html: str) -> Tuple[str, int]:
    """Последна мрежа: изречението за отлагане на медицинска помощ се заменя със сигурно. Връща (текст, брой замени)."""
    text, count = html or "", 0
    for code, sentence in health_findings(html):
        if code != "health_delay":
            continue
        core = sentence.rstrip(" .!?")
        new, n = re.subn(re.escape(core) + r"[.!?]?", HEALTH_DELAY_REPLACEMENT, text, count=1)
        if n:
            text, count = new, count + n
    text = re.sub(r"(?:" + re.escape(HEALTH_DELAY_REPLACEMENT) + r"\s*){2,}", HEALTH_DELAY_REPLACEMENT + " ", text)       # две подред замени = едно изречение
    return text.replace(HEALTH_DELAY_REPLACEMENT + " </", HEALTH_DELAY_REPLACEMENT + "</"), count


# Реална семейна биография от символика (R15): „Майка ви е била строга“; само като модел на собствените реакции и с уговорка
_FAMILY = r"(?:майка|майката|баща|бащата|родител\w*|дядо|дядото|баба|бабата|прадядо|прабаба|предци\w*)"
_PAST_FACT = (r"(?:е\s+бил\w*|са\s+били|бил\w*|били|починал\w*|напуснал\w*|изоставил\w*|страдал\w*|имал\w*|злоупотребявал\w*|разведен\w*)")
_BIO_RE = re.compile(
    rf"(?<![\w]){_FAMILY}\s+(?:ти|ви|му|ѝ|им|на\s+\w+)?\s*{_PAST_FACT}(?![\w])"                      # „Майка ви е била строга“
    rf"|(?<![\w]){_FAMILY}\s*,?\s*(?:който|която|които)\s+{_PAST_FACT}(?![\w])"                           # „родител, който е бил недостъпен“
    rf"|(?:предава\w*|унаследява\w*|наследява\w*)\s+(?:се\s+)?(?:през|от)\s+(?:родов\w+|предци\w*|рода)(?![\w])",    # „предава се през родовата линия“
    re.IGNORECASE)
# Само истинска уговорка махa изречението от нарушенията: „най-вероятно“ и „модел“ не са уговорка за факт от чужд живот
_BIO_HEDGE_RE = re.compile(r"може\s+да|символ\w*|възможно|понякога|свързва\w*|подсказва\w*|(?<![\w])ако(?![\w])|в\s+смисъл|не\s+като\s+факт", re.IGNORECASE)


def biography_findings(text: str) -> List[str]:
    return [sentence[:200] for sentence in _plain_sentences(text) if _BIO_RE.search(sentence) and not _BIO_HEDGE_RE.search(sentence)]


# Самокорекция на редактора в готовия текст („Юпитер е в ретрограден Сатурн... – всъщност Юпитер е ...“)
_EDITOR_RE = re.compile(r"(?:\.\.\.|…)\s*[–—-]?\s*(?:всъщност|по-точно|поправка|извинявам\s+се|грешка)|(?<![\w])(?:нека\s+поправя|извинявам\s+се|поправка\s*:)", re.IGNORECASE)


def editor_leaks(text: str) -> List[str]:
    return [m.group(0) for m in _EDITOR_RE.finditer(re.sub(r"<[^>]+>", " ", text or ""))]


def _remove_sentences(html: str, pattern: re.Pattern) -> Tuple[str, int]:
    # Изречение = текст без <, >, . ! ? около съвпадението (в рамките на един текстов възел)
    sentence = re.compile(r"[^<>.!?]*(?:" + pattern.pattern + r")[^<>.!?]*[.!?]?", re.IGNORECASE)
    return sentence.subn("", html)


def check_output(html: str, report_type: str = "general") -> Tuple[str, List[str]]:
    """Връща (почистен_текст, списък_с_флагове)."""
    flags: List[str] = []
    text = html or ""
    text, replaced = replace_health_delays(text)
    if replaced:
        flags.append("health_delay")
    for name, pattern in _SEVERE_RE.items():
        text, n = _remove_sentences(text, pattern)
        if n:
            flags.append(name)
    for name, pattern in _SOFT_RE.items():
        if pattern.search(text):
            flags.append(name)
    if report_type == "health":
        text += "\n" + HEALTH_NOTE_HTML
    if flags or report_type in ("health", "money"):
        text += "\n" + DISCLAIMER_HTML
    return text, flags
