def _grave_stems(text: str) -> set:
    """Основите (първите 5 букви) на тежките заболявания в текста."""
    return {m.group(0).lower()[:5] for rx in (_GRAVE_RE, _GRAVE_LOWER_RE) for m in rx.finditer(text or "")}


